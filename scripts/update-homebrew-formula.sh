#!/usr/bin/env bash
# Print the Homebrew formula for the scythe CLI on stdout.
#
# update-homebrew-formula.sh <version> <checksums-file>
#
# ~keep The checksums file is the release's `scythe_<version>_checksums.txt`, as written by
# ~keep sha256sum over the archives. A missing line aborts rather than emitting a formula with
# ~keep an empty sha256, which Homebrew would accept and then install an unverified binary.
set -euo pipefail

if [ "$#" -ne 2 ] || [ -z "$1" ] || [ -z "$2" ]; then
  echo "usage: $0 <version> <checksums-file>" >&2
  exit 1
fi

version=$1
sums=$2
[ -f "$sums" ] || {
  echo "checksums file not found: $sums" >&2
  exit 1
}
base="https://github.com/Goldziher/scythe/releases/download/v${version}"

sha_for() {
  awk -v f="scythe-$1.tar.gz" '{n=$NF; sub(/^[*]/, "", n); if (n == f) print $1}' "$sums"
}

mac_arm=$(sha_for aarch64-apple-darwin)
mac_x64=$(sha_for x86_64-apple-darwin)
for pair in "aarch64-apple-darwin:${mac_arm}" "x86_64-apple-darwin:${mac_x64}"; do
  if [ -z "${pair#*:}" ]; then
    echo "missing checksum for ${pair%%:*} in $sums" >&2
    exit 1
  fi
done

cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by scripts/update-homebrew-formula.sh — do not edit by hand.
class Scythe < Formula
  desc "Polyglot SQL-to-code generator with built-in linting and formatting"
  homepage "https://github.com/Goldziher/scythe"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/scythe-aarch64-apple-darwin.tar.gz"
      sha256 "${mac_arm}"
    end
    on_intel do
      url "${base}/scythe-x86_64-apple-darwin.tar.gz"
      sha256 "${mac_x64}"
    end
  end

  def install
    bin.install "scythe"
  end

  test do
    system "#{bin}/scythe", "--version"
  end
end
EOF
