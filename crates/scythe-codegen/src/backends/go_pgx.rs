    /// Regression test for #100: a schema with only int/string columns must
    /// not emit `"time"` or `github.com/shopspring/decimal` imports, or
    /// `go build` fails with "imported and not used".
    #[test]
    fn test_go_pgx_file_header_omits_time_and_decimal_for_int_and_string_only_schema() {
        let backend = get_backend("go-pgx", "postgresql").unwrap();
        let query = make_simple_query(
            "ListWidgets",
            "-- @name ListWidgets\n-- @returns :many\nSELECT id, name FROM widgets",
            vec![
                AnalyzedColumn {
                    name: "id".to_string(),
                    neutral_type: "int32".to_string(),
                    nullable: false,
                    ..Default::default()
                },
                AnalyzedColumn {
                    name: "name".to_string(),
                    neutral_type: "string".to_string(),
                    nullable: false,
                    ..Default::default()
                },
            ],
        );
        let code = generate_with_backend(&query, &*backend).unwrap();
        let header = backend.file_header_for_results(&[code]);

        assert!(
            !header.contains("\"time\""),
            "int/string-only schema must not import \"time\"; got:\n{header}"
        );
        assert!(
            !header.contains("shopspring/decimal"),
            "int/string-only schema must not import shopspring/decimal; got:\n{header}"
        );
        // The always-required imports must still be present, or the file
        // fails to compile for a different reason.
        assert!(header.contains("\"context\""), "got:\n{header}");
        assert!(header.contains("pgxpool"), "got:\n{header}");
    }

